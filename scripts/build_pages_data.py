"""Builds docs/data.js (data + safety rules) from the Python sources, so the
GitHub Pages demo always matches the Python app.  Run: python scripts/build_pages_data.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from core import safety  # noqa: E402

from core.faculty import FacultyDB  # noqa: E402

faculty = FacultyDB(ROOT / "data" / "faculty.csv").faculty

data = {
    "faculty": list(faculty.values()),
    "faq": json.loads((ROOT / "data" / "campus_faq.json").read_text(encoding="utf-8")),
    "patterns": safety.PATTERNS, "severity": safety.SEVERITY,
    "contacts": safety.HELP_CONTACTS, "responses": safety.RESPONSES,
    "banned": safety.BANNED_OUTPUT,
}
out = ROOT / "docs" / "data.js"
out.write_text("// generated by scripts/build_pages_data.py - do not edit\nwindow.CAMPUS_DATA = "
               + json.dumps(data, ensure_ascii=False) + ";\n", encoding="utf-8")
print("wrote", out)
